function buildMarkdown(resolved: Doubt[], role: Role) {
  const stamp = new Intl.DateTimeFormat('en', {
    dateStyle: 'long',
    timeStyle: 'short',
  }).format(new Date());
  const sourceCount = resolved.reduce((n, d) => n + d.evidence.length, 0);

  const lines = [
    '# Relay Handover — relay-labs',
    '',
    `> Verified single source of truth · ${stamp}`,
    '',
    `**${resolved.length} decisions resolved · ${sourceCount} sources traced**`,
    '',
  ];

  resolved.forEach((doubt, index) => {
    const resolution = doubt.resolutions.find(
      (r) => r.id === doubt.resolvedWith,
    );
    lines.push(`## ${index + 1}. ${doubt.title}`);
    lines.push('');
    lines.push(`- **Area:** ${doubt.area}`);
    lines.push(`- **Severity:** ${doubt.severity}`);
    lines.push(`- **Claim:** ${doubt.claim}`);
    lines.push(`- **Decision:** ${resolution?.label ?? 'Resolved'}`);
    if (resolution?.description) {
      lines.push(`- **Rationale:** ${resolution.description}`);
    }
    lines.push(`- **Confidence:** ${Math.round(doubt.confidence * 100)}%`);
    if (doubt.decision) {
      lines.push(
        `- **Decision type:** ${DECISION_LABEL[doubt.decision.type]}`,
      );
      if (doubt.decision.rationale) {
        lines.push(`- **Rationale:** ${doubt.decision.rationale}`);
      }
      if (doubt.decision.owner) {
        lines.push(`- **Accountable owner:** ${doubt.decision.owner}`);
      }
      lines.push(
        `- **Sign-off:** ${
          doubt.decision.signedOff
            ? doubt.decision.signoffName ?? doubt.decision.owner ?? 'recorded'
            : 'not required'
        }`,
      );
      lines.push(`- **Verification:** ${doubt.decision.verification}`);
    }
    if (role === 'junior' && doubt.implementation) {
      lines.push(`- **Owner:** ${doubt.implementation.owner}`);
      lines.push(`- **Repo:** ${doubt.implementation.repo}`);
      lines.push(`- **PR:** ${doubt.implementation.pr}`);
      lines.push(`- **Branch:** ${doubt.implementation.branch}`);
    }
    if (role === 'manager' && doubt.impact) {
      lines.push(`- **Budget:** ${doubt.impact.budget}`);
      lines.push(`- **Timeline:** ${doubt.impact.timeline}`);
      lines.push(`- **Risk:** ${doubt.impact.risk}`);
    }
    if (doubt.evidence.length > 0) {
      lines.push(
        `- **Citations:** ${doubt.evidence
          .map((evidence) => evidence.author)
          .join(' · ')}`,
      );
    }
    lines.push('');
  });

  lines.push('---');
  lines.push('');
  lines.push(
    '_Generated by Relay. Read-only verification across Slack, Jira, GitHub, and Notion._',
  );
  return lines.join('\n');
}

function buildJson(
  resolved: Doubt[],
  role: Role,
  packages: RemediationPackage[] | null,
) {
  return JSON.stringify(
    {
      artifact: 'relay-handover',
      project: 'relay-labs',
      version: 'v2',
      generatedAt: new Date().toISOString(),
      role,
      readiness: 100,
      stats: {
        decisions: resolved.length,
        sources: resolved.reduce((n, doubt) => n + doubt.evidence.length, 0),
        signedOff: resolved.filter((doubt) => doubt.decision?.signedOff).length,
        verified: resolved.filter(
          (doubt) => doubt.decision?.verification === 'verified',
        ).length,
        autoTriaged: resolved.filter(
          (doubt) => doubt.decision?.type === 'auto',
        ).length,
      },
      decisions: resolved.map((doubt) => ({
        id: doubt.id,
        title: doubt.title,
        area: doubt.area,
        severity: doubt.severity,
        claim: doubt.claim,
        confidence: doubt.confidence,
        resolution:
          doubt.resolutions.find((item) => item.id === doubt.resolvedWith) ??
          null,
        decision: doubt.decision ?? null,
        impact: role === 'manager' ? (doubt.impact ?? null) : null,
        implementation:
          role === 'junior' ? (doubt.implementation ?? null) : null,
        citations: doubt.evidence.map((evidence) => ({
          id: evidence.id,
          source: evidence.source,
          author: evidence.author,
          timestamp: evidence.timestamp,
          quote: evidence.quote,
          polarity: evidence.polarity,
          relevance: evidence.relevance,
          injected: Boolean(evidence.injected),
        })),
        remediation:
          packages?.find((item) => item.doubtId === doubt.id) ?? null,
      })),
    },
    null,
    2,
  );
}

function buildPatchBundle(
  resolved: Doubt[],
  packages: RemediationPackage[] | null,
) {
  const sections = resolved
    .map((doubt) =>
      packages?.find((item) => item.doubtId === doubt.id),
    )
    .filter(
      (item): item is RemediationPackage =>
        Boolean(item?.allowed && item.patch),
    )
    .map(
      (item) =>
        `# ${item.doubtId} — ${item.title}\n# ${item.area} · ${item.severity}\n${item.patch?.diff ?? ''}`,
    );

  return sections.length > 0
    ? `${sections.join('\n\n')}\n`
    : '# No deterministic patches are available for this lens.\n';
}

